function slugify(texto) {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // quita tildes/acentos
    .replace(/[^a-zA-Z0-9\s-]/g, "") // quita apóstrofes y demás símbolos
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "-");
}

